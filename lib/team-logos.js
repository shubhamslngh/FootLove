export function formatTeamDisplayName(teamName) {
  const value = String(teamName || "").trim();
  if (!value) return "";
  if (/^[A-Za-z0-9]{2,5}$/.test(value.replace(/\s+/g, ""))) {
    return value.toUpperCase();
  }

  return value
    .toLowerCase()
    .split(/\s+/)
    .map((word) => {
      if (/^[a-z]{2,5}$/.test(word) && word === word.toUpperCase()) {
        return word.toUpperCase();
      }
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(" ")
    .replace(/\bFc\b/g, "FC")
    .replace(/\bCf\b/g, "CF")
    .replace(/\bSc\b/g, "SC")
    .replace(/\bAc\b/g, "AC")
    .replace(/\bAfc\b/g, "AFC")
    .replace(/\bRb\b/g, "RB")
    .replace(/\bPsg\b/g, "PSG")
    .replace(/\bPsv\b/g, "PSV")
    .replace(/\bAik\b/g, "AIK")
    .replace(/\bIfk\b/g, "IFK");
}
