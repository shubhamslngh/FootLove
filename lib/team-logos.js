function normalizeTeamName(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function stripTokens(normalized) {
  return normalized
    .split("_")
    .filter((token) => token && !STRIP_TOKENS.has(token))
    .join("_");
}

const CLUB_LOGO_BY_STRIPPED_NAME = Object.fromEntries(
  Object.entries(CLUB_LOGO_BY_NAME).map(([name, path]) => [stripTokens(name), path]),
);

export function getClubLogoUrl(teamName) {
  const normalized = normalizeTeamName(teamName);
  if (!normalized) return null;
  const aliasTarget = CLUB_LOGO_ALIASES[normalized];
  return (
    (aliasTarget ? CLUB_LOGO_BY_NAME[aliasTarget] : null) ||
    CLUB_LOGO_BY_NAME[normalized] ||
    CLUB_LOGO_BY_STRIPPED_NAME[normalized] ||
    CLUB_LOGO_BY_STRIPPED_NAME[stripTokens(normalized)] ||
    null
  );
}

